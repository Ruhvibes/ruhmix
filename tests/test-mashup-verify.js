/* ================= browser shim + loader ================= */

function makeFakeCtx() {
  return {
    sampleRate: SR,
    createBuffer(ch, len, sr) {
      const planes = [];
      for (let c = 0; c < ch; c++) planes.push(new Float32Array(len));
      return {
        numberOfChannels: ch,
        length: len,
        sampleRate: sr,
        duration: len / sr,
        getChannelData: (c) => planes[c],
        copyToChannel: (src, c) => planes[c].set(src),
      };
    },
  };
}

// Load a www/js browser module in a vm sandbox. Returns its RM namespace
// object (e.g. sandbox.RM after the file ran), or throws with the cause.
function loadModule(srcFile, preRM) {
  const code = fs.readFileSync(srcFile, 'utf8');
  const sandbox = {};
  sandbox.window = sandbox;
  sandbox.self = sandbox;
  sandbox.globalThis = sandbox;
  sandbox.console = console;
  sandbox.Math = Math; sandbox.JSON = JSON;
  sandbox.Float32Array = Float32Array; sandbox.Float64Array = Float64Array;
  sandbox.Uint8Array = Uint8Array; sandbox.Int16Array = Int16Array;
  sandbox.Array = Array; sandbox.Object = Object; sandbox.Error = Error;
  sandbox.Number = Number; sandbox.String = String; sandbox.Boolean = Boolean;
  sandbox.Promise = Promise; sandbox.setTimeout = setTimeout;
  sandbox.clearTimeout = clearTimeout; sandbox.setInterval = setInterval;
  sandbox.clearInterval = clearInterval;
  sandbox.isFinite = isFinite; sandbox.isNaN = isNaN;
  sandbox.parseFloat = parseFloat; sandbox.parseInt = parseInt;
  const RM = preRM || {};
  sandbox.RM = RM;
  sandbox.window.RM = RM;
  vm.createContext(sandbox);
  vm.runInContext(code, sandbox, { filename: path.basename(srcFile) });
  return sandbox.RM;
}

/* ================= signal helpers ================= */

function rms(x) {
  let s = 0;
  for (let i = 0; i < x.length; i++) s += x[i] * x[i];
  return Math.sqrt(s / x.length);
}
function peak(x) {
  let p = 0;
  for (let i = 0; i < x.length; i++) { const a = Math.abs(x[i]); if (a > p) p = a; }
  return p;
}
function hasBad(x) {
  for (let i = 0; i < x.length; i++) if (!isFinite(x[i])) return true;
  return false;
}
function toMono(bufLike) {
  // Accept AudioBuffer-like, Float32Array, or {samples,sampleRate}.
  if (bufLike instanceof Float32Array) return { data: bufLike, sr: SR };
  if (bufLike && bufLike.samples instanceof Float32Array)
    return { data: bufLike.samples, sr: bufLike.sampleRate || SR };
  if (bufLike && typeof bufLike.getChannelData === 'function')
    return { data: bufLike.getChannelData(0), sr: bufLike.sampleRate || SR };
  throw new Error('cannot coerce output to mono Float32Array');
}
function toMonoSafe(bufLike) {
  try { toMono(bufLike); return true; } catch (e) { return false; }
}
// Dominant frequency via zero-crossing count (task-mandated method).
function freqByZeroCross(x, sr) {
  let zc = 0;
  for (let i = 1; i < x.length; i++)
    if ((x[i - 1] < 0 && x[i] >= 0) || (x[i - 1] >= 0 && x[i] < 0)) zc++;
  return (zc / 2) / (x.length / sr);
}

/* Normalize a detectKey() return into {root, mode, confidence}.
   Accepts the common shapes workers might use. */
const PC = { C: 0, 'C#': 1, Db: 1, D: 2, 'D#': 3, Eb: 3, E: 4, F: 5,
             'F#': 6, Gb: 6, G: 7, 'G#': 8, Ab: 8, A: 9, 'A#': 10, Bb: 10, B: 11 };
function normKey(k) {
  if (typeof k === 'string') {
    const m = k.trim().match(/^([A-G](?:#|b)?)\s*(major|minor|maj|min|m)?$/i);
    if (!m) return null;
    const root = m[1][0].toUpperCase() + m[1].slice(1);
    const mode = !m[2] || /^maj/i.test(m[2]) ? 'major' : 'minor';
    return { root, mode, pc: PC[root], confidence: NaN };
  }
  if (k && typeof k === 'object') {
    const keyStr = k.key || k.name || k.tonic || null;
    const base = keyStr ? normKey(String(keyStr)) : null;
    const root = k.root || k.tonic || (base && base.root);
    const modeRaw = k.mode || k.quality || (base && base.mode);
    if (root === undefined || root === null) return null;
    const r = String(root);
    const rNorm = r[0].toUpperCase() + r.slice(1);
    const mode = /min/i.test(String(modeRaw || '')) ? 'minor' : 'major';
    const conf = k.confidence !== undefined ? k.confidence
               : k.score !== undefined ? k.score : NaN;
    return { root: rNorm, mode, pc: PC[rNorm], confidence: Number(conf) };
  }
  return null;
}

