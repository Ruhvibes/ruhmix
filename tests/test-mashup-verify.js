function writeWavMono16(file, samples) {
  const n = samples.length;
  const buf = Buffer.alloc(44 + n * 2);
  buf.write('RIFF', 0); buf.writeUInt32LE(36 + n * 2, 4); buf.write('WAVE', 8);
  buf.write('fmt ', 12); buf.writeUInt32LE(16, 16); buf.writeUInt16LE(1, 20);
  buf.writeUInt16LE(1, 22); buf.writeUInt32LE(SR, 24); buf.writeUInt32LE(SR * 2, 28);
  buf.writeUInt16LE(2, 32); buf.writeUInt16LE(16, 34);
  buf.write('data', 36); buf.writeUInt32LE(n * 2, 40);
  for (let i = 0; i < n; i++) {
    const s = Math.max(-1, Math.min(1, samples[i]));
    buf.writeInt16LE(Math.round(s * 32767), 44 + i * 2);
  }
  fs.writeFileSync(file, buf);
}

// Tiny WAV decoder -> Float32 mono (16-bit PCM only; enough for our fixtures).
function decodeWavMono16(file) {
  const buf = fs.readFileSync(file);
  if (buf.toString('ascii', 0, 4) !== 'RIFF' || buf.toString('ascii', 8, 12) !== 'WAVE')
    throw new Error('not a WAV: ' + file);
  const fmt = buf.readUInt16LE(20), ch = buf.readUInt16LE(22), bits = buf.readUInt16LE(34);
  const sr = buf.readUInt32LE(24);
  if (fmt !== 1 || bits !== 16) throw new Error(`unsupported WAV fmt=${fmt} bits=${bits}`);
  // find 'data' chunk
  let off = 12;
  while (off + 8 <= buf.length) {
    const id = buf.toString('ascii', off, off + 4);
    const sz = buf.readUInt32LE(off + 4);
    if (id === 'data') break;
    off += 8 + sz;
  }
  const dataOff = off + 8, dataSz = buf.readUInt32LE(off + 4);
  const frames = Math.floor(dataSz / (ch * 2));
  const out = new Float32Array(frames);
  for (let i = 0; i < frames; i++) {
    let acc = 0;
    for (let c = 0; c < ch; c++) acc += buf.readInt16LE(dataOff + (i * ch + c) * 2);
    out[i] = acc / ch / 32768;
  }
  return { samples: out, sampleRate: sr };
}

function genClickTrack(bpm, secs) {
  const n = Math.floor(secs * SR);
  const out = new Float32Array(n);
  const beat = 60 / bpm;
  const clickLen = Math.floor(0.02 * SR); // 20 ms decaying 2 kHz burst
  for (let b = 0; b * beat < secs; b++) {
    const start = Math.floor(b * beat * SR);
    for (let i = 0; i < clickLen && start + i < n; i++) {
      const t = i / SR;
      const env = Math.exp(-t / 0.004);
      out[start + i] += 0.8 * env * Math.sin(2 * Math.PI * 2000 * t);
    }
  }
  return out;
}

function genChord(freqs, secs) {
  const n = Math.floor(secs * SR);
  const out = new Float32Array(n);
  const amp = 0.28;
  for (let i = 0; i < n; i++) {
    const t = i / SR;
    let s = 0;
    for (const f of freqs) s += Math.sin(2 * Math.PI * f * t);
    out[i] = (amp / freqs.length) * s;
  }
  // 10 ms raised-cosine edges so detectKey never sees a click transient
  const e = Math.floor(0.01 * SR);
  for (let i = 0; i < e; i++) {
    const w = 0.5 * (1 - Math.cos(Math.PI * i / e));
    out[i] *= w; out[n - 1 - i] *= w;
  }
  return out;
}

function genSine(freq, secs, amp) {
  const n = Math.floor(secs * SR);
  const out = new Float32Array(n);
  for (let i = 0; i < n; i++) out[i] = amp * Math.sin(2 * Math.PI * freq * i / SR);
  const e = Math.floor(0.01 * SR);
  for (let i = 0; i < e; i++) {
    const w = 0.5 * (1 - Math.cos(Math.PI * i / e));
    out[i] *= w; out[n - 1 - i] *= w;
  }
  return out;
}

